/**
 * @brief fb_skins: who wears what, and at which size it loaded here.
 */
void CG_FatBoss_Skins_f(void)
{
	int i, s, t, r, any = 0;

	for (i = 0; i < MAX_CLIENTS; i++)
	{
		char line[256] = "";

		for (s = 0; s < FB_SKIN_SLOTS; s++)
		{
			if (fbSkinLoadout[i][s])
			{
				Q_strcat(line, sizeof(line), va(" %s=%s(%.3f)", fbSkinSlotNames[s], fbSkinThemes[fbSkinLoadout[i][s] - 1].name,
				                                (double)fbSkinWear[i][s] / 1000.0));
				if (fbStattrak[i][s] >= 0)
				{
					Q_strcat(line, sizeof(line), va("^8[ST %i]^7", fbStattrak[i][s]));
				}
				if (fbStickers[i][s][0] >= 0 || fbStickers[i][s][1] >= 0 || fbStickers[i][s][2] >= 0 || fbStickers[i][s][3] >= 0)
				{
					Q_strcat(line, sizeof(line), va("[k %c%c%c%c]", fbStickers[i][s][0] >= 0 ? fbStickerChars[(int)fbStickers[i][s][0]] : '.',
					                                fbStickers[i][s][1] >= 0 ? fbStickerChars[(int)fbStickers[i][s][1]] : '.',
					                                fbStickers[i][s][2] >= 0 ? fbStickerChars[(int)fbStickers[i][s][2]] : '.',
					                                fbStickers[i][s][3] >= 0 ? fbStickerChars[(int)fbStickers[i][s][3]] : '.'));
				}
			}
			if (fbSkinWanted[i][s] != fbSkinLoadout[i][s])
			{
				Q_strcat(line, sizeof(line), va(" ^3(%s next: %s)^7", fbSkinSlotNames[s],
				                                fbSkinWanted[i][s] ? fbSkinThemes[fbSkinWanted[i][s] - 1].name : "stock"));
			}
		}
		if (line[0])
		{
			CG_Printf("%2i %s^7:%s\n", i, cgs.clientinfo[i].infoValid ? cgs.clientinfo[i].name : "?", line);
			any = 1;
		}
	}
	if (!any)
	{
		CG_Printf("FatBoss: nobody here wears a weapon skin\n");
	}
	for (i = 0; i < MAX_CLIENTS && !fbSkinPending[i]; i++)
	{
	}
	if (i < MAX_CLIENTS)
	{
		CG_Printf("^3FatBoss: changes marked \"next\" wait for the intermission, the next map or /reconnect (fb_loadskins loads them now)\n");
	}
	for (i = 0; i < FB_SKIN_THEMES; i++)
	{
		for (t = 0; t < FB_SKIN_TEXTURES; t++)
		{
			for (r = 0; r < FB_RES_COUNT; r++)
			{
				if (fbSkinShaders[i][t][r])
				{
					CG_Printf("  loaded %s/%s_%s%s\n", fbSkinThemes[i].name, fbSkinTexNames[t], fbSkinResNames[r],
					          fbSkinShaders[i][t][r] < 0 ? " ^1missing" : "");
				}
			}
		}
	}
}

static qboolean CG_FatBoss_PanelCommand(const char *cmd);

/**
 * @brief Server commands for FatBoss; returns qtrue when the command was ours.
 */
qboolean CG_FatBoss_ServerCommand(const char *cmd)
{
	if (!Q_stricmpn(cmd, "fbinv", 5) || !Q_stricmp(cmd, "fbpanel_err") || !Q_stricmp(cmd, "fbwear_ok"))
	{
		return CG_FatBoss_PanelCommand(cmd);
	}
	if (!Q_stricmp(cmd, "fbskin"))
	{
		return qtrue;           // fatboss.lua before 0.8; loadouts come in configstrings now
	}
	if (!Q_stricmp(cmd, "fbtags"))
	{
		int s;

		// the names of your own worn copies, one argument per slot ("" for none)
		for (s = 0; s < FB_SKIN_SLOTS; s++)
		{
			Q_strncpyz(fbTags[s], CG_Argv(1 + s), sizeof(fbTags[s]));
		}
		return qtrue;
	}
	if (!Q_stricmp(cmd, "fbspray"))
	{
		CG_FatBoss_ParseSpray();
		return qtrue;
	}
	if (!Q_stricmp(cmd, "fbspray_clear"))
	{
		int clientNum = Q_atoi(CG_Argv(1));

		if (clientNum >= 0 && clientNum < MAX_CLIENTS)
		{
			fbSprays[clientNum].active = qfalse;
		}
		return qtrue;
	}
	return qfalse;
}

void CG_FatBoss_AddSprays(void)
{
	int i, j, k;

	if (!fbSyncAsked && cg.snap && !cg.demoPlayback)
	{
		fbSyncAsked = qtrue;
		trap_SendClientCommand(va("fbsync %i", FATBOSS_CGAME_BUILD));
	}
	CG_FatBoss_SkinPump();
	for (i = 0; i < MAX_CLIENTS; i++)
	{
		if (!fbSprays[i].active)
		{
			continue;
		}
		for (j = 0, k = 0; j < fbSprays[i].numPolys; k += fbSprays[i].polyVerts[j], j++)
		{
			trap_R_AddPolyToScene(fbSprays[i].shader, fbSprays[i].polyVerts[j], &fbSprays[i].verts[k]);
		}
	}
}

void CG_FatBoss_ClearSprays(void)
{
	Com_Memset(fbSprays, 0, sizeof(fbSprays));
}

