static struct
{
	qboolean active;
	qboolean ending;
	int startTime;
	int endTime;
	int weapon;
	float endFraction;
	const fbInspectProfile_t *profile;
	int nextShot;                   ///< fb_inspectshots: inspect time of the next screenshot
	qboolean framed;                ///< stableFit: the first frame's framing is stored
	vec3_t frameCenterCam;          ///< stableFit: weapon centre in view space
	vec3_t frameCenterModel;        ///< stableFit: weapon centre in the hand's own frame
} fbInspect;

/// review aid, off by default: screenshot every N ms of inspect game time
static vmCvar_t fb_inspectshots;

static const fbInspectProfile_t *CG_FatBoss_InspectProfile(int weapon)
{
	int i, j;

	for (i = 0; i < (int)ARRAY_LEN(fbInspectProfiles); i++)
	{
		for (j = 0; fbInspectProfiles[i].weapons[j]; j++)
		{
			if (fbInspectProfiles[i].weapons[j] == weapon)
			{
				return &fbInspectProfiles[i];
			}
		}
	}
	return NULL;
}

/**
 * @brief Only inspect an idle, supported weapon held by the local player.
 */
static qboolean CG_FatBoss_InspectAllowed(const playerState_t *ps)
{
	const fbInspectProfile_t *profile = CG_FatBoss_InspectProfile(ps->weapon);
	usercmd_t                cmd;

	if (!profile || !cg.snap || cg.demoPlayback || cg.renderingThirdPerson
	    || cg.editingSpeakers || cg.testGun || cg.showGameView || cgs.dbShowing
	    || (cg_drawGun.integer != 1 && !(cg_drawGun.integer == 2 && profile->style == FB_STYLE_KNIFE))
	    || ps->pm_type != PM_NORMAL
	    || ps->stats[STAT_HEALTH] <= 0
	    || ps->persistant[PERS_TEAM] == TEAM_SPECTATOR
	    || (ps->pm_flags & (PMF_FOLLOW | PMF_LIMBO))
	    || (ps->eFlags & (EF_FIRING | EF_MG42_ACTIVE | EF_AAGUN_ACTIVE | EF_MOUNTEDTANK | EF_PRONE_MOVING))
	    || ps->persistant[PERS_HWEAPON_USE]
	    || cg.zoomed || cg.zoomedBinoc || cg.zoomval != 0.0f
	    || cg.weapzoomActive || cg.binocZoomTime
	    || ps->weaponstate != WEAPON_READY || cg.weaponSelect != ps->weapon)
	{
		return qfalse;
	}

	// cancel before prediction enters a firing or reload state, never consume input
	if (trap_GetUserCmd(trap_GetCurrentCmdNumber(), &cmd)
	    && ((cmd.buttons & BUTTON_ATTACK) || (cmd.wbuttons & (WBUTTON_RELOAD | WBUTTON_ATTACK2))))
	{
		return qfalse;
	}

	return qtrue;
}

static float CG_FatBoss_Ease(float fraction)
{
	if (fraction <= 0.0f)
	{
		return 0.0f;
	}
	if (fraction >= 1.0f)
	{
		return 1.0f;
	}
	return fraction * fraction * (3.0f - 2.0f * fraction);
}

static int CG_FatBoss_InspectElapsed(void)
{
	return (fbInspect.ending ? fbInspect.endTime : cg.time) - fbInspect.startTime;
}

/**
 * @brief The pose comes from time only, so it does not depend on render pass count.
 */
static float CG_FatBoss_InspectFraction(void)
{
	int elapsed, hold;

	if (!fbInspect.active || !fbInspect.profile)
	{
		return 0.0f;
	}
	if (fbInspect.ending)
	{
		elapsed = cg.time - fbInspect.endTime;
		return fbInspect.endFraction * (1.0f - CG_FatBoss_Ease((float)elapsed / FB_INSPECT_OUT_TIME));
	}

	hold    = fbInspect.profile->holdTime;
	elapsed = cg.time - fbInspect.startTime;
	if (elapsed < FB_INSPECT_IN_TIME)
	{
		return CG_FatBoss_Ease((float)elapsed / FB_INSPECT_IN_TIME);
	}
	if (elapsed < FB_INSPECT_IN_TIME + hold)
	{
		return 1.0f;
	}
	return 1.0f - CG_FatBoss_Ease((float)(elapsed - FB_INSPECT_IN_TIME - hold) / FB_INSPECT_OUT_TIME);
}

/**
 * @brief +ilookatweapon: start the inspect, or ease back on a second press.
 */
void CG_FatBoss_Inspect_f(void)
{
	if (fbInspect.active)
	{
		if (!fbInspect.ending)
		{
			fbInspect.endFraction = CG_FatBoss_InspectFraction();
			fbInspect.endTime     = cg.time;
			fbInspect.ending      = qtrue;
		}
		return;
	}
	if (!CG_FatBoss_InspectAllowed(&cg.predictedPlayerState))
	{
		return;
	}

	fbInspect.active    = qtrue;
	fbInspect.ending    = qfalse;
	fbInspect.startTime = cg.time;
	fbInspect.weapon    = cg.predictedPlayerState.weapon;
	fbInspect.profile   = CG_FatBoss_InspectProfile(fbInspect.weapon);
	fbInspect.nextShot  = 0;
	fbInspect.framed    = qfalse;
}

