void CG_FatBoss_CancelInspect(void)
{
	fbInspect.active = qfalse;
	fbInspect.ending = qfalse;
}

/**
 * @brief Gameplay actions end the inspect at once; a finished one eases out.
 */
void CG_FatBoss_UpdateInspect(const playerState_t *ps)
{
	if (!fbInspect.active)
	{
		return;
	}
	trap_Cvar_Update(&fb_inspectshots);
	if (fb_inspectshots.integer > 0 && cg.time - fbInspect.startTime >= fbInspect.nextShot)
	{
		CG_Printf("FBSHOT %d %d\n", fbInspect.weapon, fbInspect.nextShot);
		trap_SendConsoleCommand("screenshotJPEG\n");
		fbInspect.nextShot += fb_inspectshots.integer;
	}
	if (!CG_FatBoss_InspectAllowed(ps) || ps->weapon != fbInspect.weapon
	    || cg.time < fbInspect.startTime
	    || (fbInspect.ending && cg.time - fbInspect.endTime >= FB_INSPECT_OUT_TIME)
	    || (!fbInspect.ending && cg.time - fbInspect.startTime
	        >= FB_INSPECT_IN_TIME + fbInspect.profile->holdTime + FB_INSPECT_OUT_TIME))
	{
		CG_FatBoss_CancelInspect();
	}
}

/**
 * @brief Present the side, roll to examine the top, turn back, then settle.
 *
 * A manual return freezes the sequence at the button press while the overall
 * inspection blend eases out.
 */
static void CG_FatBoss_InspectAngles(vec3_t angles)
{
	typedef struct
	{
		int time;
		vec3_t angles;
	} inspectKeyframe_t;
	static const inspectKeyframe_t pistolKeyframes[] =
	{
		{    0, {  -4.0f, 70.0f, -10.0f } },
		{  700, {  -4.0f, 70.0f, -10.0f } },
		{ 1550, { -14.0f, 55.0f, -42.0f } },
		{ 2400, {   8.0f, 65.0f,  12.0f } },
		{ 3050, {  -4.0f, 70.0f, -10.0f } },
		{ 3350, {  -4.0f, 70.0f, -10.0f } }
	};
	static const inspectKeyframe_t smgKeyframes[] =
	{
		{    0, {  -7.0f, 72.0f,  -8.0f } },
		{ 1000, {  -7.0f, 72.0f,  -8.0f } },
		{ 2400, { -18.0f, 55.0f, -36.0f } },
		{ 3900, {   5.0f, 82.0f,  20.0f } },
		{ 5000, {  -7.0f, 72.0f,  -8.0f } },
		{ 5350, {  -7.0f, 72.0f,  -8.0f } }
	};
	// long guns: side on across the screen, tip the top towards the camera, turn back
	const inspectKeyframe_t *keyframes;
	int                     numKeyframes;
	int                     elapsed = CG_FatBoss_InspectElapsed();
	int                     i, j;
	float                   fraction;

	switch (fbInspect.profile->style)
	{
	case FB_STYLE_PISTOL:
		keyframes    = pistolKeyframes;
		numKeyframes = ARRAY_LEN(pistolKeyframes);
		break;
	default:
		keyframes    = smgKeyframes;
		numKeyframes = ARRAY_LEN(smgKeyframes);
		break;
	}

	for (i = 1; i < numKeyframes; i++)
	{
		if (elapsed < keyframes[i].time)
		{
			fraction = CG_FatBoss_Ease((float)(elapsed - keyframes[i - 1].time)
			                           / (keyframes[i].time - keyframes[i - 1].time));
			for (j = 0; j < 3; j++)
			{
				angles[j] = keyframes[i - 1].angles[j]
				            + fraction * (keyframes[i].angles[j] - keyframes[i - 1].angles[j]);
			}
			return;
		}
	}
	VectorCopy(keyframes[numKeyframes - 1].angles, angles);
}

/**
 * @brief Wrist twist of the knife hand: turn the blade to its other face and back.
 */
static float CG_FatBoss_KnifeSpin(void)
{
	static const struct
	{
		int time;
		float spin;
	} keyframes[] =
	{
		{    0,   0.0f },
		{ 1100,   0.0f },
		{ 2100, 150.0f },
		{ 3700, 150.0f },
		{ 4700,   0.0f },
		{ 5350,   0.0f }
	};
	int   elapsed = CG_FatBoss_InspectElapsed();
	int   i;
	float fraction;

	for (i = 1; i < (int)ARRAY_LEN(keyframes); i++)
	{
		if (elapsed < keyframes[i].time)
		{
			fraction = CG_FatBoss_Ease((float)(elapsed - keyframes[i - 1].time)
			                           / (keyframes[i].time - keyframes[i - 1].time));
			return keyframes[i - 1].spin + fraction * (keyframes[i].spin - keyframes[i - 1].spin);
		}
	}
	return keyframes[ARRAY_LEN(keyframes) - 1].spin;
}

/**
 * @brief Hold the knife up with the complete blade above the hand.
 *
 * The twist (CG_FatBoss_KnifeTwist) then turns the hand about the forearm
 * axis. Turning it about the blade axis swung the sleeve around and showed
 * its hollow inside.
 */
static void CG_FatBoss_KnifeAxis(vec3_t axis[3])
{
	vec3_t source[3], sourceTranspose[3], target[3], front;
	int    i, j;

	VectorCopy(fbInspect.profile->bladeAxis0, source[0]);
	VectorCopy(fbInspect.profile->bladeAxis1, source[1]);
	VectorNormalize(source[0]);
	VectorNormalize(source[1]);
	CrossProduct(source[0], source[1], source[2]);
	for (i = 0; i < 3; i++)
	{
		for (j = 0; j < 3; j++)
		{
			sourceTranspose[i][j] = source[j][i];
		}
	}

	// a modest upward diagonal presents the complete blade above the hand
	VectorSet(target[0], 0.10f, 0.945f, 0.311f);
	VectorNormalize(target[0]);
	VectorSet(front, -1.0f, 0.0f, 0.0f);
	VectorMA(front, -DotProduct(front, target[0]), target[0], front);
	VectorNormalize(front);
	VectorCopy(front, target[1]);
	CrossProduct(target[0], target[1], target[2]);
	MatrixMultiply(sourceTranspose, target, axis);
}

/**
 * @brief Add a model's oriented bounds in the inspection's camera coordinates.
 */
static qboolean CG_FatBoss_InspectAddBounds(const refEntity_t *hand, qhandle_t model, const char *tagName,
                                            qboolean weaponBody, qboolean blade, vec3_t mins, vec3_t maxs,
                                            vec3_t *points, int *numPoints)
{
	const fbInspectProfile_t *profile = fbInspect.profile;
	orientation_t            tag;
	vec3_t                   modelMins, modelMaxs, modelOrigin, modelAxis[3], corner;
	float                    coordinate;
	int                      i, j;

	if (!model || trap_R_LerpTag(&tag, hand, tagName, 0) < 0)
	{
		return qfalse;
	}

	VectorCopy(hand->origin, modelOrigin);
	for (i = 0; i < 3; i++)
	{
		VectorMA(modelOrigin, tag.origin[i], hand->axis[i], modelOrigin);
	}
	MatrixMultiply(tag.axis, hand->axis, modelAxis);

	if (weaponBody)
	{
		// the main models also hold the forearm; fitting it would shrink the gun
		VectorCopy(profile->bodyMins, modelMins);
		VectorCopy(profile->bodyMaxs, modelMaxs);
	}
	else
	{
		trap_R_ModelBounds(model, modelMins, modelMaxs);
	}
	for (i = 0; i < 3 && !blade; i++)
	{
		// invalid renderer bounds must never expand the fit (also rejects NaNs)
		if (!(modelMins[i] <= modelMaxs[i]) || modelMins[i] < -4096.0f || modelMaxs[i] > 4096.0f)
		{
			if (fbInspect.weapon == WP_SILENCED_COLT && !Q_stricmp(tagName, "tag_barrel6"))
			{
				// the shipped silencer reports inverted bounds; these enclose its vertices
				VectorSet(modelMins, -0.1f, -2.8f, -1.45f);
				VectorSet(modelMaxs, 10.4f, 1.4f, 2.8f);
				break;
			}
			return qfalse;
		}
	}

	for (i = 0; i < 8; i++)
	{
		VectorCopy(modelOrigin, corner);
		for (j = 0; j < 3; j++)
		{
			coordinate = blade ? profile->blade[i][j] : ((i & (1 << j)) ? modelMaxs[j] : modelMins[j]);
			VectorMA(corner, coordinate, modelAxis[j], corner);
		}
		AddPointToBounds(corner, mins, maxs);
		if (*numPoints < FB_INSPECT_MAX_POINTS)
		{
			VectorCopy(corner, points[*numPoints]);
			(*numPoints)++;
		}
	}
	return qtrue;
}

/**
 * @brief Accumulate the shifts that move one sleeve's open end past an edge.
 */
static void CG_FatBoss_InspectArmLimits(const refEntity_t *hand, const fbRim_t *rim, const vec3_t origin,
                                        float tanX, float tanY, float *rightShift, float *downShift)
{
	orientation_t tag;
	vec3_t        modelOrigin, modelAxis[3], point;
	int           i, j;

	if (trap_R_LerpTag(&tag, hand, rim->tag, 0) < 0)
	{
		return;
	}
	VectorCopy(origin, modelOrigin);
	for (i = 0; i < 3; i++)
	{
		VectorMA(modelOrigin, tag.origin[i], hand->axis[i], modelOrigin);
	}
	MatrixMultiply(tag.axis, hand->axis, modelAxis);
	for (i = 0; i < rim->numPoints; i++)
	{
		VectorCopy(modelOrigin, point);
		for (j = 0; j < 3; j++)
		{
			VectorMA(point, rim->points[i][j], modelAxis[j], point);
		}
		*rightShift = MIN(*rightShift, -1.01f * point[0] * tanX - point[1]);
		*downShift  = MIN(*downShift, -1.01f * point[0] * tanY - point[2]);
	}
}

/**
 * @brief Keep the forearm's open end outside the right or bottom edge.
 */
static void CG_FatBoss_InspectHideArmEnd(const refEntity_t *hand, float tanX, float tanY,
                                         const vec3_t *points, int numPoints, vec3_t origin)
{
	vec3_t point;
	float  rightShift = 0.0f, downShift = 0.0f;
	float  rightLimit = -999999.0f, downLimit = -999999.0f;
	int    i;

	for (i = 0; i < (int)ARRAY_LEN(fbInspect.profile->rims); i++)
	{
		if (fbInspect.profile->rims[i].tag)
		{
			CG_FatBoss_InspectArmLimits(hand, &fbInspect.profile->rims[i], origin, tanX, tanY, &rightShift, &downShift);
		}
	}

	// preserve a visible border around the weapon, including its grip and magazine
	for (i = 0; i < numPoints; i++)
	{
		VectorAdd(points[i], origin, point);
		rightLimit = MAX(rightLimit, -0.95f * point[0] * tanX - point[1]);
		downLimit  = MAX(downLimit, -0.95f * point[0] * tanY - point[2]);
	}
	if (downShift >= downLimit)
	{
		origin[2] += downShift;
	}
	else if (rightShift >= rightLimit)
	{
		origin[1] += rightShift;
	}
	else
	{
		// very unusual aspect ratios may require the corner instead of one edge
		origin[1] += MIN(0.0f, MAX(rightShift, rightLimit));
		origin[2] += MIN(0.0f, MAX(downShift, downLimit));
	}
}

/**
 * @brief Compensate only the viewmodel for the world's FOV, preserving pixels.
 */
static void CG_FatBoss_InspectProjection(float *tanX, float *tanY, vec3_t scale)
{
	float aspect = (float)cg.refdef_current->width / MAX(1, cg.refdef_current->height);

	// the virtual vertical FOV is fixed; horizontal FOV follows the actual aspect
	*tanY    = 0.75f * tanf(75.0f * (float)M_PI / 360.0f);
	*tanX    = *tanY * aspect;
	scale[0] = 1.0f;
	scale[1] = tanf(Com_Clamp(5.0f, 175.0f, cg.refdef_current->fov_x) * (float)M_PI / 360.0f) / *tanX;
	scale[2] = tanf(Com_Clamp(5.0f, 175.0f, cg.refdef_current->fov_y) * (float)M_PI / 360.0f) / *tanY;
}

static void CG_FatBoss_KnifeTwist(const refEntity_t *hand, vec3_t origin, vec3_t axis[3]);

/**
 * @brief Fit the complete weapon to a bounded screen area at the actual FOV.
 */
static qboolean CG_FatBoss_InspectTarget(const refEntity_t *hand, vec3_t targetOrigin, vec3_t targetAxis[3])
{
	const fbInspectProfile_t *profile = fbInspect.profile;
	refEntity_t              localHand = *hand;
	weaponInfo_t             *weapon   = &cg_weapons[fbInspect.weapon];
	vec3_t                   angles, mins, maxs, center, extent, localOrigin, projectionScale;
	vec3_t                   presentationAxis[3], tempAxis[3], points[FB_INSPECT_MAX_POINTS];
	float                    tanX, tanY, depth, fitX, fitY;
	int                      i, j, numPoints = 0;

	if (profile->style == FB_STYLE_KNIFE)
	{
		CG_FatBoss_KnifeAxis(localHand.axis);
	}
	else
	{
		CG_FatBoss_InspectAngles(angles);
		AnglesToAxis(angles, localHand.axis);
		// a model-only screen roll points the forearm naturally toward the bottom
		VectorSet(angles, 0.0f, 0.0f, profile->roll);
		AnglesToAxis(angles, presentationAxis);
		MatrixMultiply(localHand.axis, presentationAxis, tempAxis);
		AxisCopy(tempAxis, localHand.axis);
	}
	VectorClear(localHand.origin);
	localHand.nonNormalizedAxes = qfalse;

	if (profile->stableFit && fbInspect.framed)
	{
		// keep the weapon centre where the first frame put it: only the turn changes
		for (i = 0; i < 3; i++)
		{
			localOrigin[i] = fbInspect.frameCenterCam[i];
			for (j = 0; j < 3; j++)
			{
				localOrigin[i] -= fbInspect.frameCenterModel[j] * localHand.axis[j][i];
			}
		}
		CG_FatBoss_InspectProjection(&tanX, &tanY, projectionScale);
		goto placed;
	}

	ClearBounds(mins, maxs);

	if (profile->hasBody && !CG_FatBoss_InspectAddBounds(&localHand, weapon->weaponModel[W_FP_MODEL].model,
	                                                     "tag_weapon", qtrue, qfalse, mins, maxs, points, &numPoints))
	{
		return qfalse;
	}
	for (i = W_PART_1; i < W_MAX_PARTS; i++)
	{
		if (profile->fitParts & FB_PART(i))
		{
			CG_FatBoss_InspectAddBounds(&localHand, weapon->partModels[W_FP_MODEL][i].model,
			                            weapon->partModels[W_FP_MODEL][i].tagName, qfalse,
			                            profile->blade && i == W_PART_1, mins, maxs, points, &numPoints);
		}
	}
	if (!numPoints)
	{
		return qfalse;
	}

	for (i = 0; i < 3; i++)
	{
		center[i] = 0.5f * (mins[i] + maxs[i]);
		extent[i] = 0.5f * (maxs[i] - mins[i]);
	}
	CG_FatBoss_InspectProjection(&tanX, &tanY, projectionScale);

	// include the depth extent so even the nearest corner respects the framing
	fitX  = extent[1] / (profile->fitX * tanX);
	fitY  = extent[2] / (profile->fitY * tanY);
	depth = extent[0] + MAX(8.0f, MAX(fitX, fitY));
	VectorSet(localOrigin, depth - center[0],
	          -0.08f * (depth - extent[0]) * tanX - center[1],
	          -0.20f * (depth - extent[0]) * tanY - center[2]);
	CG_FatBoss_InspectHideArmEnd(&localHand, tanX, tanY, (const vec3_t *)points, numPoints, localOrigin);
	if (profile->stableFit)
	{
		for (i = 0; i < 3; i++)
		{
			fbInspect.frameCenterModel[i] = DotProduct(center, localHand.axis[i]);
			fbInspect.frameCenterCam[i]   = localOrigin[i] + center[i];
		}
		fbInspect.framed = qtrue;
	}

placed:
	VectorCopy(cg.refdef_current->vieworg, targetOrigin);
	for (i = 0; i < 3; i++)
	{
		VectorMA(targetOrigin, localOrigin[i] * projectionScale[i], cg.refdef_current->viewaxis[i], targetOrigin);
	}
	MatrixMultiply(localHand.axis, cg.refdef_current->viewaxis, targetAxis);
	if (profile->style == FB_STYLE_KNIFE)
	{
		CG_FatBoss_KnifeTwist(hand, targetOrigin, targetAxis);
	}
	return qtrue;
}

/**
 * @brief Turn the knife hand about the forearm axis through the wrist.
 *
 * The fit is made at no twist, so the forearm stays where it was framed and
 * the blade turns with the hand like a real wrist twist.
 */
static void CG_FatBoss_KnifeTwist(const refEntity_t *hand, vec3_t origin, vec3_t axis[3])
{
	const fbInspectProfile_t *profile = fbInspect.profile;
	orientation_t            tag;
	vec3_t                   modelOrigin, modelAxis[3], a, pivot, offset, turned[3];
	float                    angle, c, s, t, rot[3][3];
	int                      i, j;

	angle = DEG2RAD(CG_FatBoss_KnifeSpin());
	if (angle == 0.0f || trap_R_LerpTag(&tag, hand, "tag_weapon", 0) < 0)
	{
		return;
	}

	// the knife viewmodel hangs on tag_weapon: find the forearm axis in the world
	VectorCopy(origin, modelOrigin);
	for (i = 0; i < 3; i++)
	{
		VectorMA(modelOrigin, tag.origin[i], axis[i], modelOrigin);
	}
	MatrixMultiply(tag.axis, axis, modelAxis);
	VectorClear(a);
	VectorCopy(modelOrigin, pivot);
	for (i = 0; i < 3; i++)
	{
		VectorMA(a, profile->wristAxis[i], modelAxis[i], a);
		VectorMA(pivot, profile->wristPivot[i], modelAxis[i], pivot);
	}
	VectorNormalize(a);

	// rotation about the unit axis a (Rodrigues)
	c = cosf(angle);
	s = sinf(angle);
	t = 1.0f - c;
	rot[0][0] = t * a[0] * a[0] + c;        rot[0][1] = t * a[0] * a[1] - s * a[2]; rot[0][2] = t * a[0] * a[2] + s * a[1];
	rot[1][0] = t * a[0] * a[1] + s * a[2]; rot[1][1] = t * a[1] * a[1] + c;        rot[1][2] = t * a[1] * a[2] - s * a[0];
	rot[2][0] = t * a[0] * a[2] - s * a[1]; rot[2][1] = t * a[1] * a[2] + s * a[0]; rot[2][2] = t * a[2] * a[2] + c;

	for (i = 0; i < 3; i++)
	{
		for (j = 0; j < 3; j++)
		{
			turned[i][j] = DotProduct(rot[j], axis[i]);
		}
	}
	AxisCopy(turned, axis);
	VectorSubtract(origin, pivot, offset);
	for (j = 0; j < 3; j++)
	{
		origin[j] = pivot[j] + DotProduct(rot[j], offset);
	}
}

/**
 * @brief Blend from normal placement into a camera-relative inspection target.
 *
 * No camera, aiming, gameplay state, input or user cvar is modified. Normal gun
 * offsets and any incoming axis scale are smoothly removed only during inspect.
 */
void CG_FatBoss_ApplyInspect(refEntity_t *hand)
{
	float  fraction = CG_FatBoss_InspectFraction();
	float  scale[3], tanX, tanY;
	vec3_t targetOrigin, targetAxis[3], naturalAxis[3], projectionScale, localAxis;
	mat4_t naturalMatrix, targetMatrix;
	quat_t naturalQuat, targetQuat, blendedQuat;
	int    i, j;

	if (fraction <= 0.0f || !CG_FatBoss_InspectTarget(hand, targetOrigin, targetAxis))
	{
		return;
	}

	// quaternion interpolation avoids distorted or sheared axes during the turn
	AxisCopy(hand->axis, naturalAxis);
	for (i = 0; i < 3; i++)
	{
		scale[i] = VectorNormalize(naturalAxis[i]);
	}
	MatrixFromVectorsFLU(naturalMatrix, naturalAxis[0], naturalAxis[1], naturalAxis[2]);
	MatrixFromVectorsFLU(targetMatrix, targetAxis[0], targetAxis[1], targetAxis[2]);
	quat_from_mat4(naturalQuat, naturalMatrix);
	quat_from_mat4(targetQuat, targetMatrix);
	quat_slerp(naturalQuat, targetQuat, fraction, blendedQuat);
	quat_to_axis(blendedQuat, hand->axis);
	CG_FatBoss_InspectProjection(&tanX, &tanY, projectionScale);
	for (i = 0; i < 3; i++)
	{
		VectorScale(hand->axis[i], scale[i] + fraction * (1.0f - scale[i]), hand->axis[i]);
		for (j = 0; j < 3; j++)
		{
			localAxis[j] = DotProduct(hand->axis[i], cg.refdef_current->viewaxis[j])
			               * (1.0f + fraction * (projectionScale[j] - 1.0f));
		}
		VectorClear(hand->axis[i]);
		for (j = 0; j < 3; j++)
		{
			VectorMA(hand->axis[i], localAxis[j], cg.refdef_current->viewaxis[j], hand->axis[i]);
		}
		hand->origin[i] += fraction * (targetOrigin[i] - hand->origin[i]);
	}
	hand->nonNormalizedAxes = qtrue;
}

// support hands disappear halfway into the inspect and come back halfway out
#define FB_HIDE_FRACTION 0.5f

static qhandle_t fbOneHandSkins[ARRAY_LEN(fbInspectProfiles)][2];

static qboolean CG_FatBoss_Inspecting(int weaponNum)
{
	return fbInspect.active && fbInspect.profile && weaponNum == fbInspect.weapon;
}

/**
 * @brief First-person weapon part hidden while inspecting (the support hand).
 */
qboolean CG_FatBoss_HidePart(int weaponNum, int part)
{
	return CG_FatBoss_Inspecting(weaponNum) && (fbInspect.profile->hideParts & FB_PART(part))
	       && CG_FatBoss_InspectFraction() > FB_HIDE_FRACTION;
}

/**
 * @brief First-person main-model skin, swapped while inspecting to hide a support hand.
 */
qhandle_t CG_FatBoss_GunSkin(int weaponNum, int team, qhandle_t skin)
{
	qhandle_t oneHand;

	if (!CG_FatBoss_Inspecting(weaponNum) || CG_FatBoss_InspectFraction() <= FB_HIDE_FRACTION)
	{
		return skin;
	}
	oneHand = fbOneHandSkins[fbInspect.profile - fbInspectProfiles][team == TEAM_ALLIES ? 1 : 0];
	return oneHand ? oneHand : skin;
}

/*
 * Graffiti
 *
 * The server (fatboss.lua) checks the spray, picks the player's design and
 * sends "fbspray" to everyone. Each player owns at most one graffiti: a new
 * spray replaces the old one, a map restart clears them all. The image is
 * projected onto the world geometry once and redrawn every frame, so it does
 * not depend on cg_markTime and survives until it is replaced.
 */

#define FB_SPRAY_MAX_VERTS 256
#define FB_SPRAY_MAX_FRAGS 32

typedef struct
{
	qboolean active;
	qhandle_t shader;
	int numPolys;
	int polyVerts[FB_SPRAY_MAX_FRAGS];
	polyVert_t verts[FB_SPRAY_MAX_VERTS];
} fbSpray_t;

static fbSpray_t   fbSprays[MAX_CLIENTS];
static sfxHandle_t fbSpraySound;
// the graffiti already on the map come as server commands when a player joins; a cgame restart
// (vid_restart) forgets them, so the first frame of every cgame asks for them again
static qboolean fbSyncAsked;

/**
 * @brief Design names come from the server: only [a-z0-9_] reach a shader path.
 */
static qboolean CG_FatBoss_ValidDesign(const char *design)
{
	int i;

	for (i = 0; design[i]; i++)
	{
		if (i >= 32 || !((design[i] >= 'a' && design[i] <= 'z') || (design[i] >= '0' && design[i] <= '9') || design[i] == '_'))
		{
			return qfalse;
		}
	}
	return i > 0;
}

/**
 * @brief fbspray <client> <design> <x y z> <normal xyz> <up xyz> <radius> <sound 0|1>
 */
static void CG_FatBoss_ParseSpray(void)
{
	// the mark syscall writes five floats per point (xyz and a renderer UV pair)
	float          pointBuffer[FB_SPRAY_MAX_VERTS][5];
	markFragment_t fragments[FB_SPRAY_MAX_FRAGS];
	fbSpray_t      *spray;
	vec3_t         origin, normal, up, right, center, quad[4], projection, delta;
	char           design[64];
	int            clientNum, numFragments, i, j, k, first, numPoints;
	float          radius;
	qboolean       onPlane;
	static const float signs[4][2] = { { -1, -1 }, { -1, 1 }, { 1, 1 }, { 1, -1 } };

	if (trap_Argc() != 14)
	{
		return;
	}
	clientNum = Q_atoi(CG_Argv(1));
	Q_strncpyz(design, CG_Argv(2), sizeof(design));
	if (clientNum < 0 || clientNum >= MAX_CLIENTS || !CG_FatBoss_ValidDesign(design))
	{
		return;
	}
	for (i = 0; i < 3; i++)
	{
		origin[i] = Q_atof(CG_Argv(3 + i));
		normal[i] = Q_atof(CG_Argv(6 + i));
		up[i]     = Q_atof(CG_Argv(9 + i));
	}
	// the server shrinks the graffiti until all of it fits on the wall
	radius = Com_Clamp(8.0f, 48.0f, Q_atof(CG_Argv(12)));
	if (VectorNormalize(normal) < 0.5f)
	{
		return;
	}
	// keep up on the surface, then right completes the frame seen from the front
	VectorMA(up, -DotProduct(up, normal), normal, up);
	if (VectorNormalize(up) < 0.1f)
	{
		PerpendicularVector(up, normal);
	}
	CrossProduct(up, normal, right);
	VectorNormalize(right);

	spray         = &fbSprays[clientNum];
	spray->active = qfalse;

	// a square half a unit in front of the hit, projected 2 units back; a negative
	// fragment count selects the original mapping, so the UVs below stay upright
	VectorMA(origin, 0.5f, normal, center);
	VectorScale(normal, -2.0f, projection);
	for (i = 0; i < 4; i++)
	{
		VectorMA(center, signs[i][0] * radius, right, quad[i]);
		VectorMA(quad[i], signs[i][1] * radius, up, quad[i]);
	}
	numFragments = trap_CM_MarkFragments(4, (const vec3_t *)quad, projection, FB_SPRAY_MAX_VERTS,
	                                     &pointBuffer[0][0], -FB_SPRAY_MAX_FRAGS, fragments);

	spray->numPolys = 0;
	k               = 0;
	for (i = 0; i < numFragments && i < FB_SPRAY_MAX_FRAGS; i++)
	{
		first     = fragments[i].firstPoint;
		numPoints = fragments[i].numPoints;
		if (first < 0 || numPoints < 3 || numPoints > MAX_VERTS_ON_POLY || first + numPoints > FB_SPRAY_MAX_VERTS
		    || k + numPoints > FB_SPRAY_MAX_VERTS)
		{
			continue;
		}
		// stay on the same wall: uneven rock and trim stay in, a wall around a
		// corner or the far side of thin geometry does not
		{
			vec3_t e1, e2, faceNormal;

			VectorSubtract(pointBuffer[first + 1], pointBuffer[first], e1);
			VectorSubtract(pointBuffer[first + 2], pointBuffer[first], e2);
			CrossProduct(e1, e2, faceNormal);
			onPlane = VectorNormalize(faceNormal) > 0.0001f && Q_fabs(DotProduct(faceNormal, normal)) > 0.7f;
		}
		for (j = 0; onPlane && j < numPoints; j++)
		{
			VectorSubtract(pointBuffer[first + j], origin, delta);
			if (Q_fabs(DotProduct(delta, normal)) > 8.0f)
			{
				onPlane = qfalse;
			}
		}
		if (!onPlane)
		{
			continue;
		}
		for (j = 0; j < numPoints; j++)
		{
			polyVert_t *v = &spray->verts[k + j];

			// lift a hair off the surface; the shader's polygonOffset does the rest
			VectorMA(pointBuffer[first + j], 0.12f, normal, v->xyz);
			VectorSubtract(pointBuffer[first + j], origin, delta);
			v->st[0] = 0.5f + DotProduct(delta, right) / (2.0f * radius);
			v->st[1] = 0.5f - DotProduct(delta, up) / (2.0f * radius);
			// the client has no light sampling: a slightly dimmed paint does not glow in the dark
			v->modulate[0] = v->modulate[1] = v->modulate[2] = 210;
			v->modulate[3] = 255;
		}
		spray->polyVerts[spray->numPolys++] = numPoints;
		k                                  += numPoints;
	}
	spray->shader = trap_R_RegisterShader(va("fatboss/graffiti/%s", design));
	spray->active = spray->numPolys && spray->shader;
	CG_DPrintf("fbspray: client %i design %s fragments %i polys %i verts %i\n", clientNum, design, numFragments,
	           spray->numPolys, k);

	if (spray->active && Q_atoi(CG_Argv(13)) && fbSpraySound)
	{
		trap_S_StartSound(origin, ENTITYNUM_WORLD, CHAN_AUTO, fbSpraySound);
	}
}

/*
 * Weapon skins
 *
 * The server (fatboss.lua) keeps every player's FatBoss loadout in a configstring
 * of its own, FB_CS_SKINS + client number (past CS_MAX, unused by the game):
 *   "<knife> <colt> <luger> <thompson> <mp40> <graffiti>"
 * with a theme or design name, or "-", per slot. Configstrings come with the
 * gamestate, so the whole server's loadouts are known on the loading screen.
 * The skins pk3 holds each theme as a 4k, 2k and 1k texture; cg_fatboss_skins.inc
 * (generated with them) says which weapon model carries the gun texture. A model
 * that is all gun gets a custom shader, one with hands or sleeves in it gets a
 * .skin file.
 *
 * Loading a texture stalls the frame that does it (a 4k one is 64 MB to decode,
 * mipmap and upload), so every texture loads on the loading screen: your own
 * weapons in 4k (both teams' guns, a team switch needs nothing new), everybody's
 * in 1k, and everybody's graffiti. A loadout that changes during the map (a new
 * skin on the website, a player joining) waits: it is applied at once when its
 * textures are already loaded, otherwise at the intermission, on the next map, after
 * /reconnect or vid_restart, or with fb_loadskins.
 *
 * Sizes: 4k for your own first-person weapon, 1k for everybody else's (the player
 * you spectate uses the best size that is loaded). Uploading a texture takes
 * width * height * 4 bytes of hunk temp memory, and running out of it drops the
 * player from the server, so a size only loads when the hunk has room; otherwise
 * the next smaller one does.
 */

#define FB_SKIN_SLOTS    5
#define FB_SKIN_TEXTURES 6

typedef struct
{
	const char *name;
	int textures;           ///< bit per texture the theme has
} fbSkinTheme_t;

typedef struct
{
	int weapon;
	int slot;
	int tex;
	int view;               ///< W_FP_MODEL or W_TP_MODEL
	int part;               ///< -1 for the weapon model itself
	const char *skin;       ///< .skin id for models with hands in them, NULL for a custom shader
	qboolean teamSkin;      ///< .skin comes per team (sleeves)
} fbSkinModel_t;

#include "cg_fatboss_skins.inc"

#define FB_SKIN_THEMES ((int)ARRAY_LEN(fbSkinThemes))
#define FB_SKIN_MODELS ((int)ARRAY_LEN(fbSkinModels))

typedef enum
{
	FB_RES_4K,              ///< first person, your own weapon
	FB_RES_1K,              ///< third person, and everybody else's first-person weapon (spectating)
	FB_RES_COUNT
} fbSkinRes_t;

static const char *fbSkinResNames[FB_RES_COUNT] = { "4k", "1k" };
static const int  fbSkinResShift[FB_RES_COUNT]  = { 0, 4 };      ///< pixels of the 4k texture >> shift

#define FB_SKIN_HUNK_MARGIN (16 * 1024 * 1024)

static int fbSkinLoadout[MAX_CLIENTS][FB_SKIN_SLOTS];                       ///< theme + 1, 0 = stock: what is drawn
static int fbSkinWanted[MAX_CLIENTS][FB_SKIN_SLOTS];                        ///< theme + 1 the server asks for
static qboolean fbSkinPending[MAX_CLIENTS];                                 ///< wanted differs from drawn
static short fbSkinWear[MAX_CLIENTS][FB_SKIN_SLOTS];                        ///< CS2 float x 1000 of the copy drawn
static short fbSkinWearWanted[MAX_CLIENTS][FB_SKIN_SLOTS];                  ///< the same for the copy the server asks for
static int fbSkinSlotTextures[FB_SKIN_SLOTS];                               ///< bit per texture a slot uses
static int fbSkinRow[WP_NUM_WEAPONS][W_NUM_TYPES][W_MAX_PARTS + 1];         ///< fbSkinModels index + 1
static int fbSkinWeaponSlot[WP_NUM_WEAPONS];                                ///< slot + 1
// registered handles; 0 not tried yet, -1 missing
static int fbSkinShaders[FB_SKIN_THEMES][FB_SKIN_TEXTURES][FB_RES_COUNT];
static int fbSkinFiles[FB_SKIN_MODELS][FB_SKIN_THEMES][FB_RES_COUNT][2];
// the size each (theme, texture, requested size) really got
static signed char fbSkinResUsed[FB_SKIN_THEMES][FB_SKIN_TEXTURES][FB_RES_COUNT];

/*
 * Stickers and StatTrak (b13)
 *
 * A skin in the configstring can carry ":sN" (the copy is StatTrak: N enemies killed with it) and
 * ":kabcd" (four sticker places: a design's place in the graffiti table, base 36, or "."). Every
 * sticker, the StatTrak display and each lit digit is one more pass of the gun over its skin, made by
 * build_stickers.py: a shader that lays one image on a rectangle of the gun's texture (so it sits on
 * the first- and third-person model alike), or, for a model that also carries hands, a .skin file that
 * sends every other surface to fbk/nodraw. Everybody sees the stickers; the display shows on your own
 * first-person gun (and the one you spectate). Like the skins, nothing of it registers while you play:
 * the passes load on the loading screen (everybody's stickers, and all ten digits in every place of your
 * own StatTrak displays), at the intermission or with fb_loadskins; a new sticker or a new StatTrak copy
 * waits till then. The count of a display that is loaded changes at once.
 */
#include "cg_fatboss_stickers.inc"

#define FB_STICKER_CODES 36

static const char fbStickerChars[FB_STICKER_CODES + 1] = "0123456789abcdefghijklmnopqrstuvwxyz";

static int fbStattrak[MAX_CLIENTS][FB_SKIN_SLOTS];                                 ///< count shown, -1: no StatTrak
static int fbStattrakWanted[MAX_CLIENTS][FB_SKIN_SLOTS];
static signed char fbStickers[MAX_CLIENTS][FB_SKIN_SLOTS][FB_STICKER_PLACES];      ///< design drawn per place, -1 none
static signed char fbStickersWanted[MAX_CLIENTS][FB_SKIN_SLOTS][FB_STICKER_PLACES];
static char fbTags[FB_SKIN_SLOTS][24];                                             ///< names of your own worn copies (fbtags)
// pass handles, 0 not tried, -1 missing: per texture (shaders) and per model row (.skin files);
// the last digit position holds the display itself
static int fbStickerShaders[FB_SKIN_TEXTURES][FB_STICKER_PLACES][FB_STICKER_CODES];
static int fbStickerSkins[FB_SKIN_MODELS][FB_STICKER_PLACES][FB_STICKER_CODES];
static int fbDigitShaders[FB_SKIN_TEXTURES][FB_STATTRAK_DIGITS + 1][10];
static int fbDigitSkins[FB_SKIN_MODELS][FB_STATTRAK_DIGITS + 1][10];

/// the main model CG_FatBoss_WeaponSkin dressed last: the passes go on that one only
static struct
{
	int clientNum;
	int weapon;
	int view;
	qboolean on;
} fbPassFor;

static int CG_FatBoss_ThemeIndex(const char *name)
{
	int i;

	for (i = 0; i < FB_SKIN_THEMES; i++)
	{
		if (!Q_stricmp(name, fbSkinThemes[i].name))
		{
			return i;
		}
	}
	return -1;
}

/**
 * @brief Largest size up to res whose upload fits in the hunk right now.
 */
static int CG_FatBoss_SkinRes(int theme, int tex, int res)
{
	char    buf[32];
	int     megs, used, r;
	int64_t room;

	if (fbSkinResUsed[theme][tex][res])
	{
		return fbSkinResUsed[theme][tex][res] - 1;
	}
	trap_Cvar_VariableStringBuffer("com_hunkMegs", buf, sizeof(buf));
	megs = Q_atoi(buf);
	trap_Cvar_VariableStringBuffer("com_hunkused", buf, sizeof(buf));
	used = Q_atoi(buf);
	room = (int64_t)megs * 1024 * 1024 - used - FB_SKIN_HUNK_MARGIN;
	for (r = res; r < FB_RES_1K; r++)
	{
		// 4 bytes a pixel
		if (((int64_t)fbSkinTexPixels[tex] * 4 >> fbSkinResShift[r]) <= room)
		{
			break;
		}
	}
	if (r != res)
	{
		CG_Printf("FatBoss: %s %s skin at %s, the hunk has %i MB free (raise com_hunkMegs for %s)\n",
		          fbSkinThemes[theme].name, fbSkinTexNames[tex], fbSkinResNames[r], (int)(room / (1024 * 1024)),
		          fbSkinResNames[res]);
	}
	fbSkinResUsed[theme][tex][res] = (signed char)(r + 1);
	return r;
}

/**
 * @brief The shader of a skin at a size when it is loaded, else another loaded size of it, else 0 (stock).
 * Nothing loads here: drawing never stalls a frame.
 */
static qhandle_t CG_FatBoss_SkinShader(int theme, int tex, int res)
{
	int r;

	res = CG_FatBoss_SkinRes(theme, tex, res);
	if (fbSkinShaders[theme][tex][res] > 0)
	{
		return fbSkinShaders[theme][tex][res];
	}
	for (r = 0; r < FB_RES_COUNT; r++)
	{
		if (fbSkinShaders[theme][tex][r] > 0)
		{
			return fbSkinShaders[theme][tex][r];
		}
	}
	return 0;
}

/**
 * @brief Loads one skin texture, and registers the .skin files that use it (a file read, no texture work).
 */
static void CG_FatBoss_LoadShader(int theme, int tex, int res)
{
	int *h = &fbSkinShaders[theme][tex][res];
	int i, t;

	if (*h)
	{
		return;
	}
	*h = trap_R_RegisterShader(va("fatboss/skins/%s/%s_%s", fbSkinThemes[theme].name, fbSkinTexNames[tex], fbSkinResNames[res]));
	if (!*h)
	{
		*h = -1;
		return;
	}
	for (i = 0; i < FB_SKIN_MODELS; i++)
	{
		const fbSkinModel_t *m = &fbSkinModels[i];

		// third-person .skin files exist in 1k only
		if (!m->skin || m->tex != tex || (m->view == W_TP_MODEL && res != FB_RES_1K))
		{
			continue;
		}
		for (t = 0; t < (m->teamSkin ? 2 : 1); t++)
		{
			int *f = &fbSkinFiles[i][theme][res][t];

			if (!*f)
			{
				// fbs/, not models/fatboss/skins/: a name of 64 characters or more does not load
				*f = trap_R_RegisterSkin(va("fbs/%s/%s_%s%s.skin", fbSkinThemes[theme].name, m->skin,
				                            fbSkinResNames[res], m->teamSkin ? (t ? "_allied" : "_axis") : ""));
				if (!*f)
				{
					*f = -1;
				}
			}
		}
	}
}

static qhandle_t CG_FatBoss_SkinFile(int row, int theme, int res, int team)
{
	const fbSkinModel_t *m = &fbSkinModels[row];
	int                 t  = m->teamSkin && team == TEAM_ALLIES ? 1 : 0;
	int                 r;

	res = m->view == W_TP_MODEL ? FB_RES_1K : CG_FatBoss_SkinRes(theme, m->tex, res);
	if (fbSkinFiles[row][theme][res][t] > 0)
	{
		return fbSkinFiles[row][theme][res][t];
	}
	if (m->view == W_TP_MODEL)
	{
		return 0;
	}
	for (r = 0; r < FB_RES_COUNT; r++)
	{
		if (fbSkinFiles[row][theme][r][t] > 0)
		{
			return fbSkinFiles[row][theme][r][t];
		}
	}
	return 0;
}

/**
 * @brief Puts the player's skin on one weapon model (main model or a part) before it is drawn.
 * The copy's wear goes into the entity alpha: the skin shader's scratch stage (alphaGen entity,
 * alphaFunc GE128) shows the mask texels whose alpha times it reaches 128, so 127 (wear 0) shows
 * none and 255 (wear 1) every one.
 */
void CG_FatBoss_WeaponSkin(refEntity_t *re, int clientNum, int weaponNum, int view, int part, int team, int powerups)
{
	const fbSkinModel_t *m;
	int                 row, theme, res;
	qhandle_t           h;

	if (weaponNum <= WP_NONE || weaponNum >= WP_NUM_WEAPONS || !fbSkinWeaponSlot[weaponNum])
	{
		return;
	}
	// no stock code gives these weapons a custom shader, and parts share one
	// refEntity: clear what the previous part got
	re->customShader = 0;
	if (part == -1)
	{
		fbPassFor.clientNum = clientNum;
		fbPassFor.weapon    = weaponNum;
		fbPassFor.view      = view;
		fbPassFor.on        = qfalse;
	}
	if (clientNum < 0 || clientNum >= MAX_CLIENTS || view < 0 || view >= W_NUM_TYPES || part < -1 || part >= W_MAX_PARTS)
	{
		return;
	}
	row = fbSkinRow[weaponNum][view][part + 1];
	if (!row)
	{
		return;
	}
	m     = &fbSkinModels[row - 1];
	theme = fbSkinLoadout[clientNum][m->slot] - 1;
	if (theme < 0 || !(fbSkinThemes[theme].textures & (1 << m->tex)))
	{
		return;
	}
	// a disguised covert op must not give himself away by his weapon
	if (view == W_TP_MODEL && (powerups & (1 << PW_OPS_DISGUISED)))
	{
		return;
	}
	res = view == W_FP_MODEL && clientNum == cg.clientNum ? FB_RES_4K : FB_RES_1K;
	if (m->skin)
	{
		h = CG_FatBoss_SkinFile(row - 1, theme, res, team);
		if (h)
		{
			re->customSkin = h;
		}
	}
	else
	{
		h = CG_FatBoss_SkinShader(theme, m->tex, res);
		if (h)
		{
			re->customShader = h;
		}
	}
	if (h)
	{
		re->shaderRGBA[3] = (byte)MIN(255, 127 + (128 * fbSkinWear[clientNum][m->slot]) / 1000);
		if (part == -1)
		{
			fbPassFor.on = qtrue;
		}
	}
}

static int CG_FatBoss_StickerCode(char c)
{
	if (c >= '0' && c <= '9')
	{
		return c - '0';
	}
	if (c >= 'a' && c <= 'z')
	{
		return c - 'a' + 10;
	}
	return -1;
}

/**
 * @brief A model with hands (or another texture) in it that build_stickers.py made .skin files for.
 */
static qboolean CG_FatBoss_StickerModel(const fbSkinModel_t *m)
{
	int i;

	for (i = 0; m->skin && fbStickerSkinModels[i]; i++)
	{
		if (!Q_stricmp(fbStickerSkinModels[i], m->skin))
		{
			return qtrue;
		}
	}
	return qfalse;
}

/**
 * @brief One pass (s<place><code>, p, d<pos>_<digit>) for a model row: a .skin file for models with hands
 * in them, else the texture's shader. Registered the first time it is asked for; 0 when there is none.
 */
static qhandle_t CG_FatBoss_Pass(int row, int *skinHandle, int *shaderHandle, const char *pass, qboolean *isSkin, qboolean load)
{
	const fbSkinModel_t *m = &fbSkinModels[row];

	if (m->skin)
	{
		*isSkin = qtrue;
		if (!CG_FatBoss_StickerModel(m))
		{
			return 0;           // its other surfaces would get the sticker too
		}
		if (!*skinHandle && load)
		{
			*skinHandle = trap_R_RegisterSkin(va("fbk/%s/%s.skin", m->skin, pass));
			if (!*skinHandle)
			{
				*skinHandle = -1;
			}
		}
		return *skinHandle > 0 ? *skinHandle : 0;
	}
	*isSkin = qfalse;
	if (!*shaderHandle && load)
	{
		*shaderHandle = trap_R_RegisterShader(va("fbk/%s/%s", fbSkinTexNames[m->tex], pass));
		if (!*shaderHandle)
		{
			*shaderHandle = -1;
		}
	}
	return *shaderHandle > 0 ? *shaderHandle : 0;
}

static qhandle_t CG_FatBoss_StickerPass(int row, int place, int code, qboolean *isSkin, qboolean load)
{
	return CG_FatBoss_Pass(row, &fbStickerSkins[row][place][code], &fbStickerShaders[fbSkinModels[row].tex][place][code],
	                       va("s%i%c", place, fbStickerChars[code]), isSkin, load);
}

static qhandle_t CG_FatBoss_DigitPass(int row, int pos, int digit, qboolean *isSkin, qboolean load)
{
	if (pos == FB_STATTRAK_DIGITS)
	{
		return CG_FatBoss_Pass(row, &fbDigitSkins[row][pos][0], &fbDigitShaders[fbSkinModels[row].tex][pos][0], "p", isSkin, load);
	}
	return CG_FatBoss_Pass(row, &fbDigitSkins[row][pos][digit], &fbDigitShaders[fbSkinModels[row].tex][pos][digit],
	                       va("d%i_%i", pos, digit), isSkin, load);
}

static qhandle_t CG_FatBoss_GraffitiIcon(int index, qboolean load);
static qboolean CG_FatBoss_GraffitiIconKnown(int index);
static int CG_FatBoss_LoadAllGraffiti(void);

/// the handle slot a pass of a row uses: its .skin file, or its texture's shader
static int *CG_FatBoss_StickerHandle(int row, int place, int code)
{
	return fbSkinModels[row].skin ? &fbStickerSkins[row][place][code] : &fbStickerShaders[fbSkinModels[row].tex][place][code];
}

static int *CG_FatBoss_DigitHandle(int row, int pos, int digit)
{
	return fbSkinModels[row].skin ? &fbDigitSkins[row][pos][digit] : &fbDigitShaders[fbSkinModels[row].tex][pos][digit];
}

/**
 * @brief The passes a slot's wanted stickers need (third person for everybody, first person for you) and, on
 * your own guns, the StatTrak display with every digit in every place. With load, registers up to limit of
 * them (0: all) and returns how many it registered; without, returns how many are not registered yet.
 */
static int CG_FatBoss_SlotPasses(int clientNum, int slot, qboolean load, int limit)
{
	int      row, p, code, pos, d, n = 0;
	qboolean isSkin;

	for (row = 0; row < FB_SKIN_MODELS; row++)
	{
		const fbSkinModel_t *m  = &fbSkinModels[row];
		qboolean            fp = m->view == W_FP_MODEL;

		if (m->slot != slot || m->part != -1 || !fbStickerTex[m->tex] || (fp && clientNum != cg.clientNum)
		    || (m->skin && !CG_FatBoss_StickerModel(m)))
		{
			continue;
		}
		for (p = 0; p < FB_STICKER_PLACES; p++)
		{
			code = fbStickersWanted[clientNum][slot][p];
			if (code <= 0 || *CG_FatBoss_StickerHandle(row, p, code))
			{
				continue;
			}
			if (load)
			{
				CG_FatBoss_StickerPass(row, p, code, &isSkin, qtrue);
			}
			if (++n == limit)
			{
				return n;
			}
		}
		if (!fp || fbStattrakWanted[clientNum][slot] < 0)
		{
			continue;
		}
		for (pos = 0; pos <= FB_STATTRAK_DIGITS; pos++)
		{
			for (d = 0; d < (pos == FB_STATTRAK_DIGITS ? 1 : 10); d++)
			{
				if (*CG_FatBoss_DigitHandle(row, pos, d))
				{
					continue;
				}
				if (load)
				{
					CG_FatBoss_DigitPass(row, pos, d, &isSkin, qtrue);
				}
				if (++n == limit)
				{
					return n;
				}
			}
		}
	}
	// your own stickers' pictures, for the inspect card
	for (p = 0; clientNum == cg.clientNum && p < FB_STICKER_PLACES; p++)
	{
		code = fbStickersWanted[clientNum][slot][p];
		if (code <= 0 || CG_FatBoss_GraffitiIconKnown(code))
		{
			continue;
		}
		if (load)
		{
			CG_FatBoss_GraffitiIcon(code, qtrue);
		}
		if (++n == limit)
		{
			return n;
		}
	}
	return n;
}

static void CG_FatBoss_AddPass(refEntity_t *re, qhandle_t h, qboolean isSkin)
{
	if (!h)
	{
		return;
	}
	re->customSkin   = isSkin ? h : 0;
	re->customShader = isSkin ? 0 : h;
	trap_R_AddRefEntityToScene(re);
}

/**
 * @brief After the gun went into the scene: its stickers, and on a first-person gun its StatTrak display
 * (the digits from the first one that is not a leading zero; the display shows the rest dark).
 */
void CG_FatBoss_WeaponExtras(const refEntity_t *gun, int clientNum, int weaponNum, int view)
{
	refEntity_t         re;
	const fbSkinModel_t *m;
	char                text[16];
	int                 row, slot, p, code, count, first;
	qboolean            isSkin;

	if (!fbPassFor.on || fbPassFor.clientNum != clientNum || fbPassFor.weapon != weaponNum || fbPassFor.view != view)
	{
		return;
	}
	row = fbSkinRow[weaponNum][view][0] - 1;
	if (row < 0 || !fbStickerTex[fbSkinModels[row].tex])
	{
		return;
	}
	m    = &fbSkinModels[row];
	slot = m->slot;
	re   = *gun;
	for (p = 0; p < FB_STICKER_PLACES; p++)
	{
		code = fbStickers[clientNum][slot][p];
		if (code > 0)
		{
			CG_FatBoss_AddPass(&re, CG_FatBoss_StickerPass(row, p, code, &isSkin, qfalse), isSkin);
		}
	}
	count = fbStattrak[clientNum][slot];
	if (view != W_FP_MODEL || count < 0)
	{
		return;
	}
	if (!CG_FatBoss_DigitPass(row, FB_STATTRAK_DIGITS, 0, &isSkin, qfalse))
	{
		return;         // not loaded (a display you spectate): nothing, rather than a stall
	}
	CG_FatBoss_AddPass(&re, CG_FatBoss_DigitPass(row, FB_STATTRAK_DIGITS, 0, &isSkin, qfalse), isSkin);
	Com_sprintf(text, sizeof(text), "%0*i", FB_STATTRAK_DIGITS, MIN(count, 999999));
	for (first = 0; first < FB_STATTRAK_DIGITS - 1 && text[first] == '0'; first++)
	{
	}
	for (p = first; p < FB_STATTRAK_DIGITS; p++)
	{
		CG_FatBoss_AddPass(&re, CG_FatBoss_DigitPass(row, p, text[p] - '0', &isSkin, qfalse), isSkin);
	}
}

/**
 * @brief The fields after a skin's theme: "NNN" (wear x 1000), "sN" (StatTrak count), "kabcd" (stickers).
 */
static void CG_FatBoss_ReadFields(char *p, short *wear, int *st, signed char stk[FB_STICKER_PLACES])
{
	char *next;
	int  k;

	for (; p && *p; p = next)
	{
		next = strchr(p, ':');
		if (next)
		{
			*next++ = 0;
		}
		if (*p == 's')
		{
			*st = MAX(0, MIN(999999, Q_atoi(p + 1)));
		}
		else if (*p == 'k')
		{
			for (k = 0; k < FB_STICKER_PLACES && p[1 + k]; k++)
			{
				stk[k] = (signed char)CG_FatBoss_StickerCode(p[1 + k]);
			}
		}
		else if (*p >= '0' && *p <= '9')
		{
			*wear = (short)Com_Clamp(0, 1000, Q_atoi(p));
		}
	}
}

/**
 * @brief A player's loadout from their configstring: themes into wanted (theme + 1, 0 = stock), each copy's
 * wear (float x 1000, "theme:NNN"; 0 without one), the graffiti design.
 */
static void CG_FatBoss_ReadLoadout(int clientNum, int wanted[FB_SKIN_SLOTS], short wear[FB_SKIN_SLOTS], int st[FB_SKIN_SLOTS],
                                   signed char stk[FB_SKIN_SLOTS][FB_STICKER_PLACES], char *design, int designSize)
{
	char buf[MAX_STRING_CHARS];
	char *p = buf, *token, *colon;
	int  i;

	Q_strncpyz(buf, CG_ConfigString(FB_CS_SKINS + clientNum), sizeof(buf));
	Com_Memset(wanted, 0, sizeof(int) * FB_SKIN_SLOTS);
	Com_Memset(wear, 0, sizeof(short) * FB_SKIN_SLOTS);
	Com_Memset(stk, -1, sizeof(signed char) * FB_SKIN_SLOTS * FB_STICKER_PLACES);
	for (i = 0; i < FB_SKIN_SLOTS; i++)
	{
		st[i] = -1;
	}
	design[0] = 0;
	for (i = 0; i <= FB_SKIN_SLOTS; i++)
	{
		while (*p == ' ')
		{
			p++;
		}
		if (!*p)
		{
			break;
		}
		token = p;
		while (*p && *p != ' ')
		{
			p++;
		}
		if (*p)
		{
			*p++ = 0;
		}
		if (i < FB_SKIN_SLOTS)
		{
			colon = strchr(token, ':');
			if (colon)
			{
				*colon = 0;
				CG_FatBoss_ReadFields(colon + 1, &wear[i], &st[i], stk[i]);
			}
			wanted[i] = CG_FatBoss_ThemeIndex(token) + 1;
		}
		else if (CG_FatBoss_ValidDesign(token))
		{
			Q_strncpyz(design, token, designSize);
		}
	}
}

/**
 * @brief Whether a slot's textures are loaded (or known missing) at the sizes this player needs.
 */
static qboolean CG_FatBoss_SlotReady(int clientNum, int slot, int theme)
{
	int tex;

	if (theme < 0)
	{
		return qtrue;
	}
	for (tex = 0; tex < FB_SKIN_TEXTURES; tex++)
	{
		if (!(fbSkinSlotTextures[slot] & fbSkinThemes[theme].textures & (1 << tex)))
		{
			continue;
		}
		if (!fbSkinShaders[theme][tex][FB_RES_1K])
		{
			return qfalse;
		}
		if (clientNum == cg.clientNum && !fbSkinShaders[theme][tex][CG_FatBoss_SkinRes(theme, tex, FB_RES_4K)])
		{
			return qfalse;
		}
	}
	return qtrue;
}

/**
 * @brief Loads what a slot needs: 1k for third person, and 4k (or the size the hunk allows) for your own weapons.
 * Returns how many textures it loaded; with justOne it stops after the first.
 */
static int CG_FatBoss_LoadSlot(int clientNum, int slot, int theme, qboolean justOne)
{
	int tex, loaded = 0, res;

	if (theme < 0)
	{
		return 0;
	}
	for (tex = 0; tex < FB_SKIN_TEXTURES; tex++)
	{
		if (!(fbSkinSlotTextures[slot] & fbSkinThemes[theme].textures & (1 << tex)))
		{
			continue;
		}
		if (!fbSkinShaders[theme][tex][FB_RES_1K])
		{
			CG_FatBoss_LoadShader(theme, tex, FB_RES_1K);
			loaded++;
			if (justOne)
			{
				return loaded;
			}
		}
		if (clientNum == cg.clientNum)
		{
			res = CG_FatBoss_SkinRes(theme, tex, FB_RES_4K);
			if (!fbSkinShaders[theme][tex][res])
			{
				CG_FatBoss_LoadShader(theme, tex, res);
				loaded++;
				if (justOne)
				{
					return loaded;
				}
			}
		}
	}
	return loaded;
}

/**
 * @brief Draws every wanted skin whose textures are loaded by now.
 */
static void CG_FatBoss_ApplyReady(void)
{
	int i, s;

	for (i = 0; i < MAX_CLIENTS; i++)
	{
		if (!fbSkinPending[i])
		{
			continue;
		}
		fbSkinPending[i] = qfalse;
		for (s = 0; s < FB_SKIN_SLOTS; s++)
		{
			if (fbSkinLoadout[i][s] != fbSkinWanted[i][s])
			{
				if (!CG_FatBoss_SlotReady(i, s, fbSkinWanted[i][s] - 1) || CG_FatBoss_SlotPasses(i, s, qfalse, 1))
				{
					fbSkinPending[i] = qtrue;
					continue;
				}
				fbSkinLoadout[i][s] = fbSkinWanted[i][s];
			}
			// another copy of the same skin loads nothing: its wear shows at once
			fbSkinWear[i][s] = fbSkinWearWanted[i][s];
			if (CG_FatBoss_SlotPasses(i, s, qfalse, 1))
			{
				// new stickers or a new StatTrak display wait for their images; a count on a display that is
				// drawn goes on
				fbSkinPending[i] = qtrue;
				if (fbStattrak[i][s] >= 0 && fbStattrakWanted[i][s] >= 0)
				{
					fbStattrak[i][s] = fbStattrakWanted[i][s];
				}
				continue;
			}
			fbStattrak[i][s] = fbStattrakWanted[i][s];
			Com_Memcpy(fbStickers[i][s], fbStickersWanted[i][s], sizeof(fbStickers[i][s]));
		}
	}
}

/**
 * @brief On the loading screen: everybody's loadout, and every texture and graffiti it needs.
 */
void CG_FatBoss_LoadSkins(void)
{
	char design[64];
	int  i, s, textures = 0;

	for (i = 0; i < MAX_CLIENTS; i++)
	{
		CG_FatBoss_ReadLoadout(i, fbSkinWanted[i], fbSkinWearWanted[i], fbStattrakWanted[i], fbStickersWanted[i], design, sizeof(design));
		for (s = 0; s < FB_SKIN_SLOTS; s++)
		{
			textures            += CG_FatBoss_LoadSlot(i, s, fbSkinWanted[i][s] - 1, qfalse);
			textures            += CG_FatBoss_SlotPasses(i, s, qtrue, 0);
			fbSkinLoadout[i][s]  = fbSkinWanted[i][s];
			fbSkinWear[i][s]     = fbSkinWearWanted[i][s];
			fbStattrak[i][s]     = fbStattrakWanted[i][s];
			Com_Memcpy(fbStickers[i][s], fbStickersWanted[i][s], sizeof(fbStickers[i][s]));
		}
		fbSkinPending[i] = qfalse;
	}
	// every design, not only the ones worn now: a graffiti somebody picks during the map must not load
	// (and stall the game) the first time it is sprayed; they are small, and the stickers' icons too
	textures += CG_FatBoss_LoadAllGraffiti();
	CG_DPrintf("FatBoss: %i skin textures loaded\n", textures);
}

/**
 * @brief A loadout changed during the map. Applied now when nothing has to load, else it waits.
 */
qboolean CG_FatBoss_ConfigStringModified(int num)
{
	char design[64];
	int  clientNum = num - FB_CS_SKINS;

	if (clientNum < 0 || clientNum >= MAX_CLIENTS)
	{
		return qfalse;
	}
	CG_FatBoss_ReadLoadout(clientNum, fbSkinWanted[clientNum], fbSkinWearWanted[clientNum], fbStattrakWanted[clientNum],
	                       fbStickersWanted[clientNum], design, sizeof(design));
	fbSkinPending[clientNum] = qtrue;
	CG_FatBoss_ApplyReady();
	return qtrue;
}

/**
 * @brief During the intermission (and in demos) waiting skins load, one texture a frame: nobody is fighting.
 */
static void CG_FatBoss_SkinPump(void)
{
	int i, s;

	if (!cg.snap || !(cg.demoPlayback || cg.snap->ps.pm_type == PM_INTERMISSION))
	{
		return;
	}
	for (i = 0; i < MAX_CLIENTS; i++)
	{
		if (!fbSkinPending[i])
		{
			continue;
		}
		for (s = 0; s < FB_SKIN_SLOTS; s++)
		{
			if (fbSkinLoadout[i][s] != fbSkinWanted[i][s] && CG_FatBoss_LoadSlot(i, s, fbSkinWanted[i][s] - 1, qtrue))
			{
				return;
			}
			if (CG_FatBoss_SlotPasses(i, s, qtrue, 4))
			{
				return;         // a few small images a frame
			}
		}
		CG_FatBoss_ApplyReady();
	}
}

/**
 * @brief fb_loadskins: load every waiting skin now (it stalls the game a moment).
 */
void CG_FatBoss_LoadPending_f(void)
{
	int i, s, textures = 0;

	for (i = 0; i < MAX_CLIENTS; i++)
	{
		for (s = 0; fbSkinPending[i] && s < FB_SKIN_SLOTS; s++)
		{
			textures += CG_FatBoss_LoadSlot(i, s, fbSkinWanted[i][s] - 1, qfalse);
			CG_FatBoss_SlotPasses(i, s, qtrue, 0);
		}
	}
	CG_FatBoss_ApplyReady();
	CG_Printf("FatBoss: %i skin texture%s loaded\n", textures, textures == 1 ? "" : "s");
}

